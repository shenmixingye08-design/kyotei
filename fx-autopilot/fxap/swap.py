_cache: dict = {}


def rate(ccy: str, t: pd.Timestamp) -> float:
    """t 時点の政策金利（年率、小数）。"""
    key = (ccy, t.year, t.month)
    if key not in _cache:
        ym = f"{t.year:04d}-{t.month:02d}"
        v = POLICY[ccy][0][1]
        for m, r in POLICY[ccy]:
            if m <= ym:
                v = r
            else:
                break
        _cache[key] = v / 100.0
    return _cache[key]


def nightly_rate(base: str, quote: str, side: int, t: pd.Timestamp, markup: float) -> float:
    """建玉 1 泊あたりの受取(+)/支払(-) 率（想定元本に対する割合）。side=+1 買い / -1 売り。"""
    diff = (rate(base, t) - rate(quote, t)) * side
    return (diff - markup) / 365.0


def rollover_days(t: pd.Timestamp) -> int:
    """21:00 UTC の足でロールオーバー。水曜は 3 日分（週末分）。"""
    if t.hour != 21 or t.weekday() > 4:
        return 0
    return 3 if t.weekday() == 2 else 1


def carry_lagged(base: str, quote: str, t: pd.Timestamp, lag_days: int = 31) -> float:
    """シグナル用のキャリー（年率の政策金利差 base - quote）。月内の政策変更を先取りしないよう 1 か月遅らせる。"""
    tt = t - pd.Timedelta(days=lag_days)
    return rate(base, tt) - rate(quote, tt)
